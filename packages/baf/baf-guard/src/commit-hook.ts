/**
 * Commit-time protected-paths 防线 (2026-10-18 项目工程 1.3, 客户决策: git 提交
 * 时对受保护路径再校验一次，命中即阻止并提示)。The tool-layer guards fence the
 * write/edit/shell tools every preset reaches, but an interpreter one-liner
 * (`node -e fs.writeFileSync(...)`) still mutates the tree — this is the last
 * line of defense BEFORE the change lands in history: a managed pre-commit
 * hook rejects any commit whose staged files touch a `guard.protectedPaths`
 * entry.
 *
 * Layout: `.git/hooks/pre-commit` is a thin POSIX sh shim (regenerated, marked
 * baf-dsh-managed, chains any pre-existing user hook via `pre-commit.user`);
 * the checker itself is `.baf/hooks/pre-commit-check.cjs` — plain Node, zero
 * dependencies, living under the git-managed (and itself protected) `.baf/`
 * tree so enterprises share it with the baseline.
 * @module @deepseek-ai/dsh-baf-guard/commit-hook
 */

import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { normalizeRel, matchesPathEntry } from './policy.ts'

/** Marker line every managed shim starts with (also the ownership test). */
export const HOOK_MARKER = '# baf-dsh-managed pre-commit (AI protected-paths commit guard)'

/** Outcome of an install attempt. */
export interface CommitHookInstallResult {
  readonly ok: boolean
  readonly message?: string
}

/**
 * Staged-file ↔ protected-entry membership, shared by the in-process checker
 * tests and the generated `.cjs` (which carries its own copy — the hook must
 * stay dependency-free). Paths normalize to `/`; entries may end `/**`.
 */
export function stagedViolations(files: readonly string[], protectedPaths: readonly string[]): readonly string[] {
  const entries = protectedPaths.filter(entry => entry.trim() !== '<enterprise-tbd>')
  return files.map(file => normalizeRel(file)).filter(rel =>
    entries.some(entry => matchesPathEntry(rel, entry)))
}

/**
 * Line-scan `guard:` → `protectedPaths` out of a baseline text. Tolerant by
 * design (a hook must not brick commits over formatting): an unreadable
 * shape yields an empty list, matching the tool guard's placeholder skip.
 */
export function parseHookProtectedPaths(text: string): readonly string[] {
  const lines = text.split(/\r?\n/)
  const guardIndex = lines.findIndex(line => /^guard:\s*(#.*)?$/.test(line))
  if (guardIndex === -1) return []
  for (let index = guardIndex + 1; index < lines.length; index += 1) {
    const body = lines[index] ?? ''
    if (body.trim() === '') continue
    if (!body.startsWith(' ')) break
    const key = /^(\s+)protectedPaths:\s*(.*)$/.exec(body)
    if (key === null) continue
    const rest = (key[2] ?? '').trim()
    const indent = key[1] ?? '  '
    const inline = /^\[(.*)\]$/.exec(rest)
    if (inline !== null) {
      return (inline[1] ?? '').split(',').map(s => s.trim().replace(/^['"]|['"]$/g, ''))
        .filter(s => s !== '' && s !== '<enterprise-tbd>')
    }
    const out: string[] = []
    for (let ahead = index + 1; ahead < lines.length; ahead += 1) {
      const entry = lines[ahead] ?? ''
      if (entry.trim() === '') continue
      const item = new RegExp(`^\\s{${indent.length + 1},}-\\s+(.+)$`).exec(entry)
      if (item === null) break
      const value = item[1]?.trim() ?? ''
      if (value !== '' && value !== '<enterprise-tbd>') out.push(value)
    }
    return out
  }
  return []
}

/** The checker script content. Plain CJS Node, zero deps, fail-open on a
 * missing/unparsable baseline (the product writer owns that file's shape). */
export function checkerScript(): string {
  return [
    '#!/usr/bin/env node',
    '// ' + HOOK_MARKER + ' — checker. Regenerated by baf-dsh (设置→工作流→项目工程).',
    "'use strict'",
    'const { execFileSync } = require("node:child_process")',
    'const { existsSync, readFileSync } = require("node:fs")',
    'const { join } = require("node:path")',
    'const root = execFileSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim()',
    'const baselinePath = join(root, ".baf", "baseline.yml")',
    'if (!existsSync(baselinePath)) process.exit(0)',
    'let paths = []',
    'try {',
    '  const text = readFileSync(baselinePath, "utf8")',
    '  const lines = text.split(/\\r?\\n/)',
    '  const guardIndex = lines.findIndex(line => /^guard:\\s*(#.*)?$/.test(line))',
    '  if (guardIndex !== -1) {',
    '    for (let i = guardIndex + 1; i < lines.length; i++) {',
    '      const body = lines[i] || ""',
    '      if (body.trim() === "") continue',
    '      if (!body.startsWith(" ")) break',
    '      const key = /^(\\s+)protectedPaths:\\s*(.*)$/.exec(body)',
    '      if (key === null) continue',
    '      const rest = (key[2] || "").trim()',
    '      const inline = /^\\[(.*)\\]$/.exec(rest)',
    '      if (inline !== null) {',
    '        paths = inline[1].split(",").map(s => s.trim().replace(/^[\'"]|[\'"]$/g, ""))',
    '          .filter(s => s !== "" && s !== "<enterprise-tbd>")',
    '      } else {',
    '        const out = []',
    '        for (let j = i + 1; j < lines.length; j++) {',
    '          const entry = lines[j] || ""',
    '          if (entry.trim() === "") continue',
    '          const item = new RegExp("^\\\\s+-\\\\s+(.+)$").exec(entry)',
    '          if (item === null) break',
    '          const value = item[1].trim()',
    '          if (value !== "<enterprise-tbd>") out.push(value)',
    '        }',
    '        paths = out',
    '      }',
    '      break',
    '    }',
    '  }',
    '} catch (err) {',
    '  console.error("[baf-dsh] pre-commit: baseline unreadable (" + err.message + "); skipping protected-paths check")',
    '  process.exit(0)',
    '}',
    'if (paths.length === 0) process.exit(0)',
    'const staged = execFileSync("git", ["diff", "--cached", "--name-only"], { encoding: "utf8" })',
    '  .split(/\\r?\\n/).filter(s => s !== "")',
    'const norm = p => p.replace(/\\\\/g, "/").replace(/^\\.\\//, "")',
    'const hits = staged.filter(file => paths.some(entry => {',
    '  const base = entry.replace(/\\/\\*{1,2}$/, "").replace(/\\/$/, "")',
    '  if (base === "") return false',
    '  const rel = norm(file)',
    '  return rel === base || rel.startsWith(base + "/")',
    '}))',
    'if (hits.length > 0) {',
    '  console.error("[baf-dsh] 提交被拒绝：以下文件位于 AI 禁改路径（.baf/baseline.yml guard.protectedPaths）：")',
    '  for (const hit of hits) console.error("  - " + hit)',
    '  console.error("这些路径不允许 AI 修改。若为人工有意变更，请仓库所有者在自己的终端确认后提交。")',
    '  process.exit(1)',
    '}',
    'process.exit(0)',
    ''].join('\n')
}

/** The `.git/hooks/pre-commit` shim. Chains `pre-commit.user` when present. */
export function shimScript(): string {
  return [
    '#!/bin/sh',
    HOOK_MARKER + ' — do not edit; baf-dsh regenerates this file.',
    'root="$(cd "$(dirname "$0")/../.." && pwd)"',
    'if ! command -v node >/dev/null 2>&1; then',
    '  echo "[baf-dsh] pre-commit: node not found; skipping protected-paths check" >&2',
    '  exit 0',
    'fi',
    'node "$root/.baf/hooks/pre-commit-check.cjs" || exit 1',
    'user="$root/.git/hooks/pre-commit.user"',
    'if [ -f "$user" ]; then',
    '  sh "$user" || exit 1',
    'fi',
    'exit 0',
    ''].join('\n')
}

/**
 * Ownership test for a pre-commit shim text. The shim's FIRST line is the
 * shebang (`#!/bin/sh`) — the marker rides the second line — so a plain
 * `startsWith` would disown our own shim (and a reinstall would then clobber
 * the preserved `pre-commit.user` with a managed copy). Any of the first
 * three lines carrying the marker counts as managed.
 */
export function isManagedShim(text: string): boolean {
  return text.split(/\r?\n/).slice(0, 3).some(line => line.startsWith(HOOK_MARKER))
}

/** Is the workspace's pre-commit hook currently ours? */
export async function commitGuardHookInstalled(workspaceRoot: string): Promise<boolean> {
  try {
    const shim = await readFile(join(workspaceRoot, '.git', 'hooks', 'pre-commit'), 'utf8')
    return isManagedShim(shim)
  } catch {
    return false
  }
}

/**
 * Install (or refresh) the commit 防线 in a workspace.
 * Idempotent; an existing non-managed user hook is preserved as
 * `pre-commit.user` and chained after our check.
 * @param workspaceRoot - absolute workspace root (a git repository).
 * @returns ok, or a message when the workspace shape refuses the install.
 */
export async function installCommitGuardHook(workspaceRoot: string): Promise<CommitHookInstallResult> {
  const hookDir = join(workspaceRoot, '.git', 'hooks')
  const shimPath = join(hookDir, 'pre-commit')
  try {
    await mkdir(join(workspaceRoot, '.baf', 'hooks'), { recursive: true })
    await writeFile(join(workspaceRoot, '.baf', 'hooks', 'pre-commit-check.cjs'), checkerScript(), 'utf8')
    let existing: string | undefined
    try {
      existing = await readFile(shimPath, 'utf8')
    } catch {
      existing = undefined
    }
    if (existing !== undefined && !isManagedShim(existing)) {
      const preserved = join(hookDir, 'pre-commit.user')
      const preservedExists = await readFile(preserved, 'utf8').then(() => true, () => false)
      // A preserved user hook already waiting means a previous install kept
      // the customer's original — the current shim content is ours, so only
      // a NOT-yet-preserved user hook moves aside now.
      if (!preservedExists) await rename(shimPath, preserved)
    }
    await writeFile(shimPath, shimScript(), 'utf8')
    return { ok: true }
  } catch (error) {
    return {
      ok: false,
      message: error instanceof Error ? error.message : String(error),
    }
  }
}
