/** @brief  校验 cfg 非空；Init 入口卫语句，避免空指针解引用。 */
static bool Module_ValidateCfg(const void *cfg)
{
    return cfg != NULL;
}

/**
 * @brief  初始化本模块运行时；须在首次业务调用前执行一次。
 * @param  cfg  配置指针；不可为 NULL；字段含义见模块 README「配置项」。
 * @return 成功返回 0；cfg 非法返回负值（调用方不得继续调用其它接口）。
 */
int32_t Module_Init(const void *cfg)
{
    if (!Module_ValidateCfg(cfg))
    {
        return -1;
    }
    (void)cfg;
    return 0;
}

